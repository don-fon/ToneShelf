"""Regenerate matching Go/TypeScript width tables from pinned Unicode data."""
from pathlib import Path
import subprocess
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
VERSION = '17.0.0'
CACHE = ROOT / '.cache' / 'unicode-width' / VERSION
CACHE.mkdir(parents=True, exist_ok=True)


def source(name):
    target = CACHE / name
    if not target.exists():
        target.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(f'https://www.unicode.org/Public/{VERSION}/ucd/{name}') as response:
            target.write_bytes(response.read())
    return target.read_text(encoding='utf-8')


def ranges(data, properties):
    values = []
    for line in data.splitlines():
        fields = line.split('#')[0].strip().split(';')
        if len(fields) < 2 or fields[1].strip() not in properties:
            continue
        span = fields[0].strip().split('..')
        values.append((int(span[0], 16), int(span[-1], 16)))
    result = []
    for start, end in sorted(values):
        if result and start <= result[-1][1] + 1:
            result[-1] = (result[-1][0], max(end, result[-1][1]))
        else:
            result.append((start, end))
    return [item for pair in result for item in pair]


east = source('EastAsianWidth.txt')
emoji = source('emoji/emoji-data.txt')
categories = source('extracted/DerivedGeneralCategory.txt')
tables = {
    'wide': ranges(east, {'W', 'F'}),
    'emojiPresentation': ranges(emoji, {'Emoji_Presentation'}),
    'emoji': ranges(emoji, {'Emoji'}),
    'pictographic': ranges(emoji, {'Extended_Pictographic'}),
    'marks': ranges(categories, {'Mn', 'Mc', 'Me'}),
}
header = f'// Generated by scripts/generate-tag-width-data.py from Unicode {VERSION}; do not edit.\n// Source: https://www.unicode.org/Public/{VERSION}/ucd/\n// License: scripts/unicode-LICENSE.txt\n'
ts, go = [header], [header, '\npackage tagwidth\n']
for name, values in tables.items():
    lines = ['  ' + ', '.join(hex(v) for v in values[i:i+12]) + ',' for i in range(0, len(values), 12)]
    ts.append(f'export const {name}: readonly number[] = [\n' + '\n'.join(lines) + '\n]\n')
    go.append(f'var {name} = [...]rune{{\n' + '\n'.join(lines) + '\n}\n')
go_path = ROOT / 'apps/server/internal/tagwidth/data.go'
go_path.parent.mkdir(parents=True, exist_ok=True)
go_path.write_text('\n'.join(go), encoding='utf-8')
subprocess.run(['gofmt', '-w', str(go_path)], check=True)
(ROOT / 'packages/player-policy/src/tag-width-data.ts').write_text('\n'.join(ts), encoding='utf-8')
license_path = ROOT / 'scripts/unicode-LICENSE.txt'
if not license_path.exists():
    with urllib.request.urlopen('https://www.unicode.org/license.txt') as response:
        license_path.write_bytes(response.read())
