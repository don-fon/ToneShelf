it('treats a touch double-tap as exclusive selection without letting its trailing click undo it', () => {
  function Filter() { const [enabled,setEnabled]=useState<string[]|undefined>(['_untagged','jp','rock']); return <TagFilter tags={tags} enabled={enabled ?? []} onChange={setEnabled}/> }
  render(<Filter/>)
  const tap=(button:HTMLElement,time:number) => {
    fireEvent.pointerDown(button)
    const up=new Event('pointerup',{bubbles:true});Object.defineProperties(up,{pointerType:{value:'touch'},timeStamp:{value:time}});fireEvent(button,up)
    const click=new MouseEvent('click',{bubbles:true});Object.defineProperty(click,'timeStamp',{value:time+1});fireEvent(button,click)
  }
  const jp=screen.getByRole('button',{name:'标签 日语'})
  tap(jp,100);tap(jp,250)
  expect(jp.getAttribute('aria-pressed')).toBe('true')
  expect(screen.getByRole('button',{name:'标签 Rock'}).getAttribute('aria-pressed')).toBe('false')
  expect(screen.getByRole('button',{name:'标签 无'}).getAttribute('aria-pressed')).toBe('false')
  tap(jp,1000)
  expect(jp.getAttribute('aria-pressed')).toBe('false')
})
